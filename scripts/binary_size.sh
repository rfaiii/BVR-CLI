#!/usr/bin/env bash
# Build the release-shaped binary and fail if it grew past the recorded
# budget. Run with --update to move the budget to the current size.
set -euo pipefail

cd "$(dirname "$0")/.."

BASELINE=".github/binary-size.env"
# Fixed stub instead of the real version: the number has to be comparable
# between a contributor laptop and CI, and a version string that changes every
# release would add noise the budget is not meant to absorb.
STUB_VERSION="0.0.0-sizecheck"

# Same shape as the goreleaser builds block, so this measures the artifact that
# gets shipped rather than whatever a laptop builds for itself.
build_binary() {
  local out=$1
  CGO_ENABLED=0 GOEXPERIMENT=greenteagc GOOS=linux GOARCH=amd64 \
    go build -trimpath \
    -ldflags="-s -w -X github.com/richavery/bvr-cli/internal/version.Version=${STUB_VERSION}" \
    -o "$out/bvr" .
}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
build_binary "$tmp"

bytes=$(wc -c <"$tmp/bvr" | tr -d ' ')
meb=$(awk 'BEGIN{printf "%.2f", '"$bytes"' / 1048576}')

if [[ "${1:-}" == "--update" ]]; then
  mkdir -p "$(dirname "$BASELINE")"
  cat >"$BASELINE" <<EOF
# Generated by: scripts/binary_size.sh --update
# linux/amd64 release-shaped binary, version stub ${STUB_VERSION}.
SIZE_BYTES=${bytes}
SIZE_TOLERANCE_BYTES=1048576
EOF
  echo "wrote ${BASELINE}: ${bytes} bytes (${meb} MiB)"
  exit 0
fi

if [[ ! -f "$BASELINE" ]]; then
  echo "no baseline at ${BASELINE}; create it with: scripts/binary_size.sh --update" >&2
  exit 1
fi
# shellcheck source=/dev/null
source "$BASELINE"

budget=$((SIZE_BYTES + SIZE_TOLERANCE_BYTES))
if ((bytes > budget)); then
  echo "::error::binary is ${bytes} bytes (${meb} MiB), over the ${budget} byte budget"
  echo "If the growth is intended, move the budget: scripts/binary_size.sh --update"
  exit 1
fi

echo "| binary size | ${meb} MiB (${bytes} bytes, budget ${budget}) |"
