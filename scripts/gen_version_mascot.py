#!/usr/bin/env python3
"""Regenerate internal/cmd/version_mascot.go from the beaver sprite.

The `--version` mascot is a baked, palette-quantized pixel sprite rather than a
runtime PNG decode: the CLI prints it once at startup, so keeping the pixels as
source data avoids an image decoder in the hot path and guarantees the art is
identical on every terminal.

Usage:
    python3 scripts/gen_version_mascot.py [--src resources/img/beaver.png]
                                          [--cols 36] [--check]

The source must be an RGBA PNG whose background is already transparent. The
generator samples the sprite into a `cols`-wide grid whose height preserves the
source aspect ratio, snaps every cell to the four-tone brand ramp, and writes a
Go file with one row per string literal.
"""

from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

import numpy as np
from PIL import Image

# Four-tone ramp sampled from the artwork, brightest pinned to the CLI accent
# (#3BF66B) so the mascot matches the help and banner colors.
PALETTE = [
    (19, 40, 22),
    (28, 110, 52),
    (44, 180, 84),
    (59, 246, 107),
]

# Fraction of a cell that must be opaque before the cell counts as artwork.
# Below this the cell is emitted as transparent.
COVERAGE = 0.30

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SRC = REPO_ROOT / "resources" / "img" / "beaver.png"
OUT_PATH = REPO_ROOT / "internal" / "cmd" / "version_mascot.go"


def rel(path: pathlib.Path) -> str:
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)

TEMPLATE = '''// Code generated by scripts/gen_version_mascot.py from {src}. DO NOT EDIT.

package cmd

import (
	"strings"

	"charm.land/lipgloss/v2"
)

// mascotPalette maps sprite digits 1-4 to the four-tone beaver ramp. The
// brightest entry is the CLI accent color used across help and banners.
var mascotPalette = [4]string{{
	"#{c0}", "#{c1}", "#{c2}", "#{c3}",
}}

// mascotRows is the beaver sprite: {cols} cells wide, {rows} pixel rows tall.
// A space is transparent and 1-4 index mascotPalette. It renders as {outh}
// terminal rows because each character cell carries two pixel rows.
var mascotRows = []string{{
{rows_src}
}}

// renderVersionMascot paints the sprite with 24-bit half blocks. Each character
// stacks two pixel rows: the top pixel becomes the glyph's foreground and the
// bottom its background, so the artwork keeps a 1:1 pixel aspect in a terminal
// whose cells are twice as tall as they are wide.
func renderVersionMascot() string {{
	width := len(mascotRows[0])

	// cell returns the hex color at column i, or "" when the pixel is
	// transparent.
	cell := func(s string, i int) string {{
		if i >= len(s) {{
			return ""
		}}
		switch c := s[i]; c {{
		case '1', '2', '3', '4':
			return mascotPalette[c-'1']
		default:
			return ""
		}}
	}}

	out := make([]string, 0, len(mascotRows)/2)
	for r := 0; r < len(mascotRows); r += 2 {{
		var b strings.Builder
		for c := range width {{
			top, bottom := cell(mascotRows[r], c), cell(mascotRows[r+1], c)
			switch {{
			case top == "" && bottom == "":
				b.WriteByte(' ')
			case top != "" && bottom == "":
				b.WriteString(lipgloss.NewStyle().
					Foreground(lipgloss.Color(top)).Render("\\u2580"))
			case top == "" && bottom != "":
				b.WriteString(lipgloss.NewStyle().
					Foreground(lipgloss.Color(bottom)).Render("\\u2584"))
			default:
				b.WriteString(lipgloss.NewStyle().
					Foreground(lipgloss.Color(top)).
					Background(lipgloss.Color(bottom)).
					Render("\\u2580"))
			}}
		}}
		out = append(out, b.String())
	}}
	return strings.Join(out, "\\n")
}}
'''


def sample(path: pathlib.Path, cols: int) -> np.ndarray:
    """Downsample an RGBA sprite to a (rows, cols) grid of palette indices."""
    img = Image.open(path).convert("RGBA")
    src = np.asarray(img)
    h, w = src.shape[:2]
    rows = int(round(h * cols / w))

    flat = np.full((rows, cols), -1, dtype=np.int8)
    for i in range(rows):
        y0, y1 = int(i * h / rows), int((i + 1) * h / rows)
        for j in range(cols):
            x0, x1 = int(j * w / cols), int((j + 1) * w / cols)
            block = src[y0:y1, x0:x1].reshape(-1, 4)
            visible = block[block[:, 3] > 0]
            if len(visible) < len(block) * COVERAGE:
                continue
            # Median per channel resists the JPEG ringing baked into the art.
            color = np.median(visible[:, :3], axis=0)
            dists = ((np.array(PALETTE, dtype=float) - color) ** 2).sum(axis=1)
            flat[i, j] = int(dists.argmin())
    return flat


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--src", type=pathlib.Path, default=DEFAULT_SRC)
    ap.add_argument("--cols", type=int, default=36)
    ap.add_argument("--out", type=pathlib.Path, default=OUT_PATH)
    ap.add_argument("--check", action="store_true", help="fail if the file would change")
    args = ap.parse_args()

    grid = sample(args.src, args.cols)
    rows, cols = grid.shape
    if rows % 2:
        rows -= 1

    rows_src = "\n".join(
        '\t"' + "".join(" " if v < 0 else str(v + 1) for v in grid[i][:cols]) + '",'
        for i in range(rows)
    )
    body = TEMPLATE.format(
        src=rel(args.src),
        cols=cols,
        rows=rows,
        outh=rows // 2,
        c0="%02X%02X%02X" % PALETTE[0],
        c1="%02X%02X%02X" % PALETTE[1],
        c2="%02X%02X%02X" % PALETTE[2],
        c3="%02X%02X%02X" % PALETTE[3],
        rows_src=rows_src,
    )

    try:
        formatted = subprocess.run(
            ["gofumpt", "-"], input=body.encode(), capture_output=True, check=True
        ).stdout.decode()
    except (FileNotFoundError, subprocess.CalledProcessError):
        formatted = body

    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != formatted:
            print(f"stale: {rel(args.out)} needs regeneration", file=sys.stderr)
            return 1
        return 0

    args.out.write_text(formatted)
    print(f"wrote {rel(args.out)} ({cols}x{rows} px, {rows // 2} terminal rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
